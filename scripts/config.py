#!/usr/bin/env python3
"""Generate and inspect the DC-Chip Kconfig configuration."""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import sys


REPO_ROOT = Path(__file__).resolve().parents[1]
KCONFIGLIB_DIR = REPO_ROOT / "tools" / "kconfiglib"
sys.path.insert(0, str(KCONFIGLIB_DIR))

import kconfiglib  # noqa: E402


DCONFIG = REPO_ROOT / "Dconfig"
DEFAULT_DEFCONFIG = REPO_ROOT / "configs" / "default_defconfig"
SYMBOL_NAMES = ("DC_SIM_SDB", "DC_SIM_WAVE", "DC_SIM_NVBOARD")


class ConfigError(Exception):
    """Expected configuration input error."""


def _new_kconfig() -> kconfiglib.Kconfig:
    os.environ["CONFIG_"] = "CONFIG_"
    os.environ["srctree"] = str(REPO_ROOT)
    return kconfiglib.Kconfig(str(DCONFIG), warn=True, warn_to_stderr=True)


def _load(kconf: kconfiglib.Kconfig, config_path: Path) -> Path:
    source = config_path if config_path.exists() else DEFAULT_DEFCONFIG
    kconf.load_config(str(source))
    return source


def _write_if_changed(path: Path, contents: str) -> bool:
    try:
        if path.read_text(encoding="utf-8") == contents:
            return False
    except FileNotFoundError:
        pass

    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    try:
        temporary.write_text(contents, encoding="utf-8")
        os.replace(temporary, path)
    finally:
        try:
            temporary.unlink()
        except FileNotFoundError:
            pass
    return True


def _auto_conf_contents(kconf: kconfiglib.Kconfig) -> str:
    lines = ["# Generated by scripts/config.py. Do not edit.\n"]
    lines.extend(
        f"CONFIG_{name}={kconf.syms[name].str_value}\n"
        for name in SYMBOL_NAMES
    )
    return "".join(lines)


def _header_contents(kconf: kconfiglib.Kconfig) -> str:
    lines = [
        "/* Generated by scripts/config.py. Do not edit. */\n",
        "#ifndef DC_CHIP_CONFIG_H\n",
        "#define DC_CHIP_CONFIG_H\n",
        "\n",
    ]
    for name in SYMBOL_NAMES:
        if kconf.syms[name].str_value == "y":
            lines.append(f"#define CONFIG_{name} 1\n")
    lines.extend(["\n", "#endif  /* DC_CHIP_CONFIG_H */\n"])
    return "".join(lines)


def _write_configuration(
    kconf: kconfiglib.Kconfig, config_path: Path, output_dir: Path
) -> None:
    config_path.parent.mkdir(parents=True, exist_ok=True)
    config_message = kconf.write_config(str(config_path), header="", save_old=False)
    auto_conf = output_dir / "auto.conf"
    config_header = output_dir / "config.h"
    auto_changed = _write_if_changed(auto_conf, _auto_conf_contents(kconf))
    header_changed = _write_if_changed(config_header, _header_contents(kconf))
    print(config_message)
    print(
        "Configuration outputs synchronized: "
        f"{auto_conf} ({'updated' if auto_changed else 'unchanged'}), "
        f"{config_header} ({'updated' if header_changed else 'unchanged'})"
    )


def _parse_assignments(assignments: list[str]) -> list[tuple[str, str]]:
    parsed: list[tuple[str, str]] = []
    seen: set[str] = set()
    for assignment in assignments:
        if assignment.count("=") != 1:
            raise ConfigError(
                f"invalid assignment '{assignment}'; expected NAME=y or NAME=n"
            )
        name, value = assignment.split("=", 1)
        if name in seen:
            raise ConfigError(f"duplicate assignment for '{name}'")
        seen.add(name)
        if name not in SYMBOL_NAMES:
            raise ConfigError(f"unknown configuration symbol '{name}'")
        if value not in ("y", "n"):
            raise ConfigError(
                f"invalid value '{value}' for '{name}'; expected lowercase y or n"
            )
        parsed.append((name, value))
    return parsed


def _set_assignments(
    kconf: kconfiglib.Kconfig, assignments: list[tuple[str, str]]
) -> None:
    for name, value in assignments:
        desired = kconfiglib.STR_TO_TRI[value]
        symbol = kconf.syms[name]
        if desired not in symbol.assignable:
            raise ConfigError(
                f"cannot assign '{value}' to '{name}' under current constraints"
            )

    for name, value in assignments:
        kconf.syms[name].set_value(value)

    for name, value in assignments:
        if kconf.syms[name].str_value != value:
            raise ConfigError(
                f"assignment '{name}={value}' is not satisfiable under current constraints"
            )


def _show(kconf: kconfiglib.Kconfig) -> None:
    for name in SYMBOL_NAMES:
        print(f"CONFIG_{name}={kconf.syms[name].str_value}")


def _path_from_argument(value: str | None, default: Path) -> Path:
    if value is None:
        return default
    return Path(value).expanduser().resolve()


def _parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Manage the DC-Chip Dconfig configuration"
    )
    parser.add_argument(
        "--config",
        metavar="PATH",
        help="configuration file (default: repository .config)",
    )
    parser.add_argument(
        "--output-dir",
        metavar="DIR",
        help="generated output directory (default: repository build/config)",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)
    subparsers.add_parser("default", help="load and write the default defconfig")
    set_parser = subparsers.add_parser("set", help="set one or more boolean options")
    set_parser.add_argument("assignments", nargs="+", metavar="NAME=y|n")
    subparsers.add_parser("show", help="show the effective configuration")
    subparsers.add_parser("sync", help="normalize and generate configuration outputs")
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = _parse_args(argv)
    config_path = _path_from_argument(args.config, REPO_ROOT / ".config")
    output_dir = _path_from_argument(args.output_dir, REPO_ROOT / "build" / "config")

    try:
        assignments = (
            _parse_assignments(args.assignments) if args.command == "set" else []
        )
        kconf = _new_kconfig()

        if args.command == "default":
            kconf.load_config(str(DEFAULT_DEFCONFIG))
            _write_configuration(kconf, config_path, output_dir)
        elif args.command == "set":
            _load(kconf, config_path)
            _set_assignments(kconf, assignments)
            _write_configuration(kconf, config_path, output_dir)
        elif args.command == "show":
            _load(kconf, config_path)
            _show(kconf)
        elif args.command == "sync":
            _load(kconf, config_path)
            _write_configuration(kconf, config_path, output_dir)
        else:
            raise ConfigError(f"unsupported command '{args.command}'")
    except (ConfigError, OSError, kconfiglib.KconfigError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
